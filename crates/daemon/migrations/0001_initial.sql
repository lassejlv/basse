-- The schema of the SQLite store at user_version 2, in Postgres types.
-- `seq` columns replace SQLite's implicit rowid as the insertion-order tie-breaker.

CREATE TABLE servers (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    name TEXT NOT NULL UNIQUE,
    kind TEXT NOT NULL,
    host TEXT,
    "user" TEXT,
    port INTEGER,
    status TEXT NOT NULL DEFAULT 'unknown',
    proxy TEXT NOT NULL DEFAULT 'missing',
    docker_version TEXT,
    last_checked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE projects (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE environments (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (project_id, name)
);

CREATE TABLE services (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    environment_id TEXT NOT NULL REFERENCES environments(id) ON DELETE CASCADE,
    server_id TEXT NOT NULL REFERENCES servers(id),
    name TEXT NOT NULL,
    source JSONB NOT NULL,
    port INTEGER,
    command TEXT,
    restart TEXT NOT NULL,
    health_path TEXT,
    stopped BOOLEAN NOT NULL DEFAULT FALSE,
    public_port INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (environment_id, name)
);

CREATE TABLE env_vars (
    service_id TEXT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    secret BOOLEAN NOT NULL,
    PRIMARY KEY (service_id, key)
);

CREATE TABLE domains (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    service_id TEXT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    host TEXT NOT NULL UNIQUE,
    port INTEGER,
    tls BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE volumes (
    id TEXT PRIMARY KEY,
    seq BIGINT GENERATED ALWAYS AS IDENTITY,
    service_id TEXT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    mount_path TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (service_id, name)
);

CREATE TABLE deployments (
    id TEXT PRIMARY KEY,
    service_id TEXT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    server_id TEXT NOT NULL,
    number BIGINT NOT NULL,
    status TEXT NOT NULL,
    trigger TEXT NOT NULL,
    commit_sha TEXT,
    commit_message TEXT,
    image TEXT,
    container_id TEXT,
    steps JSONB NOT NULL,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    UNIQUE (service_id, number)
);
CREATE INDEX deployments_status ON deployments(status);

CREATE TABLE activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMPTZ NOT NULL,
    level TEXT NOT NULL,
    service_id TEXT,
    service_name TEXT,
    project_id TEXT,
    message TEXT NOT NULL,
    detail TEXT
);

CREATE TABLE backups (
    id TEXT PRIMARY KEY,
    service_id TEXT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    number BIGINT NOT NULL,
    status TEXT NOT NULL,
    trigger TEXT NOT NULL,
    file_name TEXT NOT NULL,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    error TEXT,
    storage TEXT NOT NULL DEFAULT 'local',
    storage_id TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    UNIQUE (service_id, number)
);
CREATE INDEX backups_status ON backups(status);

CREATE TABLE backup_schedules (
    service_id TEXT PRIMARY KEY REFERENCES services(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL,
    hour_utc INTEGER NOT NULL,
    keep BIGINT NOT NULL,
    last_run_at TIMESTAMPTZ
);
